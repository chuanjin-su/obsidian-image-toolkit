import type { App, TFile } from "obsidian";
import { assertStaticImage } from "./embeds";
import { bytesEqual, normalizeBackupFolder, saveImage } from "./storage";

export interface ImageBackup {
  file: TFile;
  path: string;
  timestamp: number;
  collision: number;
}

function sourceParent(path: string): string {
  const slash = path.lastIndexOf("/");
  return slash < 0 ? "" : path.slice(0, slash);
}

function sourceFilename(path: string): { basename: string; extension: string } {
  const filename = path.slice(path.lastIndexOf("/") + 1);
  const dot = filename.lastIndexOf(".");
  if (dot < 0) return { basename: filename, extension: "" };
  return { basename: filename.slice(0, dot), extension: filename.slice(dot) };
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** Find exact backup names generated by saveImage for this source and backup folder. */
export function findImageBackups(app: App, source: TFile, backupFolder: string): ImageBackup[] {
  const normalizedFolder = normalizeBackupFolder(backupFolder);
  const { basename, extension } = sourceFilename(source.path);
  const directory = [normalizedFolder, sourceParent(source.path)].filter(Boolean).join("/");
  const filenamePattern = new RegExp(
    `^${escapeRegExp(basename)}-backup-(\\d+)(?:-(\\d+))?${escapeRegExp(extension)}$`,
  );
  const backups: ImageBackup[] = [];

  for (const file of app.vault.getFiles()) {
    const slash = file.path.lastIndexOf("/");
    const fileDirectory = slash < 0 ? "" : file.path.slice(0, slash);
    if (fileDirectory !== directory) continue;

    const match = filenamePattern.exec(file.path.slice(slash + 1));
    if (!match) continue;
    const timestamp = Number(match[1]);
    const collision = match[2] === undefined ? 0 : Number(match[2]);
    // Only canonical, safe integers can be emitted by saveImage's numeric counters.
    if (
      !Number.isSafeInteger(timestamp) || timestamp < 0 || !Number.isFinite(new Date(timestamp).getTime()) || String(timestamp) !== match[1] ||
      !Number.isSafeInteger(collision) || collision < 0 || String(collision) !== (match[2] ?? "0") ||
      (match[2] !== undefined && collision === 0)
    ) continue;

    backups.push({ file, path: file.path, timestamp, collision });
  }

  return backups.sort((left, right) => right.timestamp - left.timestamp || right.collision - left.collision);
}

function assertBackupStillPresent(
  app: App,
  source: TFile,
  version: ImageBackup,
  backupFolder: string,
): void {
  const stillAvailable = findImageBackups(app, source, backupFolder).some((candidate) =>
    candidate.file === version.file &&
    candidate.path === version.path &&
    candidate.timestamp === version.timestamp &&
    candidate.collision === version.collision &&
    version.file.path === version.path &&
    app.vault.getAbstractFileByPath(version.path) === version.file,
  );
  if (!stillAvailable) throw new Error("The selected backup is no longer available for this image.");
}

/** Restore a selected backup only if it is still the same version shown to the user. */
export async function restoreImageBackup(
  app: App,
  source: TFile,
  version: ImageBackup,
  originalBytes: ArrayBuffer,
  backupBytes: ArrayBuffer,
  backupFolder: string,
): Promise<{ path: string; backupPath?: string }> {
  const selectedVersion: ImageBackup = { ...version };
  const originalSnapshot = originalBytes.slice(0);
  const backupSnapshot = backupBytes.slice(0);
  assertBackupStillPresent(app, source, selectedVersion, backupFolder);
  const restoredBytes = await app.vault.readBinary(selectedVersion.file);
  assertBackupStillPresent(app, source, selectedVersion, backupFolder);
  if (!bytesEqual(restoredBytes, backupSnapshot)) {
    throw new Error("The selected backup changed after it was previewed.");
  }

  assertStaticImage(restoredBytes, source.extension.toLowerCase());
  return saveImage(app, source, originalSnapshot, restoredBytes, {
    backupEnabled: true,
    backupFolder,
  });
}
